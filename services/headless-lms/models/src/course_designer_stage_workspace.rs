/// ABC learning design activity types used by the student workload calculator.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, ToSchema, Default)]
#[serde(rename_all = "snake_case")]
pub enum DesignWorkloadActivityType {
    AcquisitionAudio,
    AcquisitionVideo,
    #[default]
    AcquisitionReading,
    Discussion,
    Collaboration,
    Investigation,
    Practice,
    Production,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, ToSchema, Default)]
#[serde(rename_all = "snake_case", default)]
pub struct DesignWorkloadActivity {
    /// Generated by the client.
    pub id: Uuid,
    pub title: String,
    pub activity_type: DesignWorkloadActivityType,
    /// How many times the activity occurs in the course.
    pub count: u32,
    /// Estimated student time for one occurrence, in minutes.
    pub minutes_each: u32,
}

impl DesignWorkspaceV1 {
    pub fn validate(&self) -> ModelResult<()> {
        check_list_len("learning goals", self.learning_goals.len(), MAX_LIST_ITEMS)?;
        for goal in &self.learning_goals {
            check_text_len("A learning goal", goal, MAX_LONG_TEXT_CHARS)?;
        }
        check_list_len("chapters", self.chapters.len(), MAX_LIST_ITEMS)?;
        for chapter in &self.chapters {
            check_text_len("A chapter title", &chapter.title, MAX_SHORT_TEXT_CHARS)?;
            check_list_len(
                "learning objectives in a chapter",
                chapter.learning_objectives.len(),
                MAX_LIST_ITEMS,
            )?;
            for objective in &chapter.learning_objectives {
                check_text_len("A learning objective", objective, MAX_LONG_TEXT_CHARS)?;
            }
            check_list_len("topics in a chapter", chapter.topics.len(), MAX_LIST_ITEMS)?;
            for topic in &chapter.topics {
                check_text_len("A topic title", &topic.title, MAX_SHORT_TEXT_CHARS)?;
            }
        }
        check_list_len(
            "workload activities",
            self.workload_activities.len(),
            MAX_WORKLOAD_ACTIVITIES,
        )?;
        for activity in &self.workload_activities {
            check_text_len(
                "A workload activity title",
                &activity.title,
                MAX_SHORT_TEXT_CHARS,
            )?;
            if activity.count > MAX_WORKLOAD_AMOUNT || activity.minutes_each > MAX_WORKLOAD_AMOUNT {
                return Err(ModelError::new(
                    ModelErrorType::InvalidRequest,
                    format!(
                        "Workload activity count and minutes must be at most {MAX_WORKLOAD_AMOUNT}."
                    ),
                    None,
                ));
            }
        }
        Ok(())
    }
}

fn check_list_len(what: &str, len: usize, max: usize) -> ModelResult<()> {
    if len > max {
        return Err(ModelError::new(
            ModelErrorType::InvalidRequest,
            format!("Too many {what}: at most {max} allowed."),
            None,
        ));
    }
    Ok(())
}

fn check_text_len(what: &str, text: &str, max_chars: usize) -> ModelResult<()> {
    if text.chars().count() > max_chars {
        return Err(ModelError::new(
            ModelErrorType::InvalidRequest,
            format!("{what} is too long: at most {max_chars} characters allowed."),
            None,
        ));
    }
    Ok(())
}

/// Parses `workspace_data` JSON from the DB into a typed envelope.
pub fn parse_workspace_data(
    value: Option<serde_json::Value>,
) -> ModelResult<Option<CourseDesignerStageWorkspace>> {
    match value {
        None => Ok(None),
        Some(v) if v.is_null() => Ok(None),
        Some(v) => {
            let parsed: CourseDesignerStageWorkspace = serde_json::from_value(v).map_err(|e| {
                ModelError::new(
                    ModelErrorType::InvalidRequest,
                    format!("Invalid workspace_data: {e}"),
                    None,
                )
            })?;
            parsed.validate()?;
            Ok(Some(parsed))
        }
    }
}

/// Validates and serializes a workspace for storage.
pub fn workspace_to_json(
    workspace: &CourseDesignerStageWorkspace,
) -> ModelResult<serde_json::Value> {
    workspace.validate()?;
    let value = serde_json::to_value(workspace).map_err(|e| {
        ModelError::new(
            ModelErrorType::Json,
            format!("Failed to serialize workspace: {e}"),
            None,
        )
    })?;
    if value.to_string().len() > MAX_WORKSPACE_JSON_BYTES {
        return Err(ModelError::new(
            ModelErrorType::InvalidRequest,
            "Workspace is too large to save.".to_string(),
            None,
        ));
    }
    Ok(value)
}

