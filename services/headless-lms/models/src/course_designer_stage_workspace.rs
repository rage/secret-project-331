//! Serialized JSON shapes for the stage workspace forms (`workspace_data` on `course_designer_plan_stages`).

use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

use crate::course_designer_plans::CourseDesignerStage;
use crate::prelude::*;

/// Bounds the stored JSON so one autosave cannot grow a stage row without limit.
const MAX_WORKSPACE_JSON_BYTES: usize = 512 * 1024;
const MAX_SHORT_TEXT_CHARS: usize = 500;
const MAX_LONG_TEXT_CHARS: usize = 20_000;
const MAX_LIST_ITEMS: usize = 100;
const MAX_WORKLOAD_ACTIVITIES: usize = 200;
const MAX_WORKLOAD_AMOUNT: u32 = 10_000;

/// Discriminant for forward-compatible workspace payloads stored in `workspace_data`.
///
/// Each schema belongs to exactly one stage; see [`CourseDesignerStageWorkspace::stage`].
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, ToSchema)]
#[serde(tag = "schema", content = "payload", rename_all = "snake_case")]
pub enum CourseDesignerStageWorkspace {
    AnalysisV1(AnalysisWorkspaceV1),
    DesignV1(DesignWorkspaceV1),
}

impl CourseDesignerStageWorkspace {
    /// The stage whose `workspace_data` may hold this schema.
    pub fn stage(&self) -> CourseDesignerStage {
        match self {
            Self::AnalysisV1(_) => CourseDesignerStage::Analysis,
            Self::DesignV1(_) => CourseDesignerStage::Design,
        }
    }

    pub fn validate(&self) -> ModelResult<()> {
        match self {
            Self::AnalysisV1(a) => a.validate(),
            Self::DesignV1(d) => d.validate(),
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, ToSchema)]
#[serde(rename_all = "snake_case")]
pub enum AnalysisCourseType {
    Compulsory,
    Elective,
}

